"""The migrations: they match the models, and they go down and up again cleanly."""

import asyncio

from alembic import command
from alembic.util.exc import AutogenerateDiffsDetected
from sqlalchemy import inspect
from sqlalchemy.ext.asyncio import create_async_engine

from apply.store.sql import downgrade, migrate
from apply.store.sql.migrate import alembic_config, current, head
from apply.store.sql.models import Base


def tables(url: str) -> set[str]:
    async def read() -> set[str]:
        engine = create_async_engine(url)
        async with engine.connect() as conn:
            names = await conn.run_sync(lambda c: set(inspect(c).get_table_names()))
        await engine.dispose()
        return names

    return asyncio.run(read())


def test_the_models_and_the_migrations_agree(pg_url):
    try:
        command.check(alembic_config(pg_url))
    except AutogenerateDiffsDetected as exc:  # pragma: no cover - the message is the point
        raise AssertionError(f"The models changed without a migration: {exc}") from None


def test_down_and_up_again(pg_url):
    expected = {t.name for t in Base.metadata.sorted_tables}
    assert expected <= tables(pg_url)
    downgrade(pg_url, "base")
    assert tables(pg_url) & expected == set()
    migrate(pg_url)
    assert expected <= tables(pg_url)
    assert asyncio.run(current(pg_url)) == head()


def test_gender_choices_are_relabelled_male_and_female(pg_url):
    """0014: a saved gender answer keeps its value; its choices read "Male" and "Female", Male first."""
    from sqlalchemy import select
    from sqlalchemy.ext.asyncio import async_sessionmaker

    from apply.store.sql.models import Answer, Pack, User

    old = [
        {"value": "decline", "label": {"en": "Decline to answer"}},
        {"value": "woman", "label": {"en": "Woman", "ne": "महिला"}},
        {"value": "man", "label": {"en": "Man", "ne": "पुरुष"}},
        {"value": "non_binary", "label": {"en": "Non-binary"}},
    ]

    async def run(work):
        engine = create_async_engine(pg_url)
        async with async_sessionmaker(engine)() as session:
            result = await work(session)
            await session.commit()
        await engine.dispose()
        return result

    async def seed(session):
        if not await session.scalar(select(Pack).where(Pack.key == "job")):  # the app adds it at start-up
            session.add(
                Pack(
                    key="job",
                    version="1",
                    label={},
                    description={},
                    profile_schema={},
                    opportunity_schema={},
                    document_types=[],
                )
            )
        user = User(email="relabel@example.com", password_hash="x", is_owner=False)
        session.add(user)
        await session.flush()
        answer = Answer(
            owner_id=user.id,
            pack="job",
            key="gender",
            question={"en": "Gender"},
            answer="woman",
            answer_type="choice",
            choices=old,
            is_sensitive=True,
            source="pack",
            position=0,
        )
        session.add(answer)
        await session.flush()
        return answer.id

    async def read(session):
        row = await session.get(Answer, answer_id)
        return row.answer, row.choices

    downgrade(pg_url, "0013")
    try:
        answer_id = asyncio.run(run(seed))
        migrate(pg_url)
        value, choices = asyncio.run(run(read))
        assert value == "woman"
        assert [(c["value"], c["label"]["en"]) for c in choices] == [
            ("decline", "Decline to answer"),
            ("man", "Male"),
            ("woman", "Female"),
            ("non_binary", "Non-binary"),
        ]
        assert choices[1]["label"]["ne"] == "पुरुष"
    finally:
        migrate(pg_url)
        asyncio.run(run(lambda s: s.execute(User.__table__.delete().where(User.email == "relabel@example.com"))))
